CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255),
    display_name VARCHAR(100) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    profile_image_url VARCHAR(500),
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    provider VARCHAR(20) NOT NULL DEFAULT 'LOCAL',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN')),
    CONSTRAINT ck_users_provider CHECK (provider IN ('LOCAL', 'KAKAO', 'GOOGLE')),
    CONSTRAINT ck_users_local_password CHECK (provider <> 'LOCAL' OR password_hash IS NOT NULL)
);

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_refresh_tokens_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_refresh_tokens_revocation CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

CREATE TABLE sellers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    brand_name VARCHAR(100) NOT NULL,
    contact_email VARCHAR(254) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    rejection_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_sellers PRIMARY KEY (id),
    CONSTRAINT uq_sellers_user UNIQUE (user_id),
    CONSTRAINT fk_sellers_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_sellers_reviewer FOREIGN KEY (reviewed_by) REFERENCES users (id),
    CONSTRAINT ck_sellers_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_sellers_review CHECK (
        (status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL AND rejection_reason IS NULL)
        OR (status = 'APPROVED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NULL)
        OR (status = 'REJECTED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NOT NULL)
    )
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_categories PRIMARY KEY (id),
    CONSTRAINT uq_categories_code UNIQUE (code)
);

CREATE TABLE drops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    seller_id BIGINT NOT NULL,
    category_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    name VARCHAR(200),
    description TEXT,
    shipping_fee BIGINT,
    shipping_notice TEXT,
    sale_starts_at TIMESTAMPTZ,
    sale_ends_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    grab_started_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    close_reason VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_drops PRIMARY KEY (id),
    CONSTRAINT fk_drops_seller FOREIGN KEY (seller_id) REFERENCES sellers (id),
    CONSTRAINT fk_drops_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_drops_status CHECK (status IN ('DRAFT', 'WISH', 'GRAB', 'ENDED', 'CANCELED')),
    CONSTRAINT ck_drops_shipping_fee CHECK (shipping_fee IS NULL OR shipping_fee >= 0),
    CONSTRAINT ck_drops_sale_period CHECK (
        sale_starts_at IS NULL OR sale_ends_at IS NULL OR sale_starts_at < sale_ends_at
    ),
    CONSTRAINT ck_drops_close_reason CHECK (
        close_reason IS NULL OR close_reason IN ('TIME_EXPIRED', 'SOLD_OUT', 'SELLER_CANCELED')
    ),
    CONSTRAINT ck_drops_published_fields CHECK (
        status NOT IN ('WISH', 'GRAB', 'ENDED')
        OR (
            category_id IS NOT NULL
            AND name IS NOT NULL
            AND description IS NOT NULL
            AND shipping_fee IS NOT NULL
            AND shipping_notice IS NOT NULL
            AND sale_starts_at IS NOT NULL
            AND sale_ends_at IS NOT NULL
            AND published_at IS NOT NULL
        )
    ),
    CONSTRAINT ck_drops_grab_started_at CHECK (
        status NOT IN ('GRAB', 'ENDED') OR grab_started_at IS NOT NULL
    ),
    CONSTRAINT ck_drops_closed CHECK (
        status NOT IN ('ENDED', 'CANCELED') OR (closed_at IS NOT NULL AND close_reason IS NOT NULL)
    )
);

CREATE TABLE drop_images (
