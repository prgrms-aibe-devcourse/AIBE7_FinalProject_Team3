    CONSTRAINT ck_drop_option_values_sort CHECK (sort_order >= 0)
);

CREATE TABLE drop_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    drop_id BIGINT NOT NULL,
    unit_price BIGINT NOT NULL,
    total_quantity INT NOT NULL,
    reserved_quantity INT NOT NULL DEFAULT 0,
    sold_quantity INT NOT NULL DEFAULT 0,
    withheld_quantity INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_drop_options PRIMARY KEY (id),
    CONSTRAINT uq_drop_options_id_drop UNIQUE (id, drop_id),
    CONSTRAINT fk_drop_options_drop FOREIGN KEY (drop_id) REFERENCES drops (id),
    CONSTRAINT ck_drop_options_price CHECK (unit_price >= 0),
    CONSTRAINT ck_drop_options_quantities CHECK (
        total_quantity >= 0
        AND reserved_quantity >= 0
        AND sold_quantity >= 0
        AND withheld_quantity >= 0
        AND reserved_quantity + sold_quantity + withheld_quantity <= total_quantity
    ),
    CONSTRAINT ck_drop_options_sort CHECK (sort_order >= 0)
);

CREATE TABLE drop_option_value_maps (
    option_id BIGINT NOT NULL,
