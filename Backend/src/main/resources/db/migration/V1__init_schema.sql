    value_id BIGINT NOT NULL,
    drop_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_drop_option_value_maps PRIMARY KEY (option_id, group_id),
    CONSTRAINT fk_option_maps_option FOREIGN KEY (option_id, drop_id)
        REFERENCES drop_options (id, drop_id),
    CONSTRAINT fk_option_maps_group FOREIGN KEY (group_id, drop_id)
        REFERENCES drop_option_groups (id, drop_id),
    CONSTRAINT fk_option_maps_value FOREIGN KEY (value_id, group_id)
        REFERENCES drop_option_values (id, group_id)
);

CREATE TABLE wishes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    drop_id BIGINT NOT NULL,
    activated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    canceled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_wishes PRIMARY KEY (id),
    CONSTRAINT uq_wishes_user_drop UNIQUE (user_id, drop_id),
    CONSTRAINT fk_wishes_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_wishes_drop FOREIGN KEY (drop_id) REFERENCES drops (id),
    CONSTRAINT ck_wishes_canceled_at CHECK (canceled_at IS NULL OR canceled_at >= activated_at)
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_number VARCHAR(64) NOT NULL,
    buyer_id BIGINT NOT NULL,
    drop_id BIGINT NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PAYMENT_PENDING',
    product_name_snapshot VARCHAR(200) NOT NULL,
    seller_name_snapshot VARCHAR(100) NOT NULL,
    items_amount BIGINT NOT NULL,
    shipping_amount BIGINT NOT NULL,
    total_amount BIGINT NOT NULL,
    recipient_name VARCHAR(100) NOT NULL,
    recipient_phone VARCHAR(30) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    address_line1 VARCHAR(300) NOT NULL,
    address_line2 VARCHAR(300),
    delivery_memo VARCHAR(300),
    payment_expires_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ,
    canceled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT uq_orders_order_number UNIQUE (order_number),
    CONSTRAINT uq_orders_buyer_idempotency UNIQUE (buyer_id, idempotency_key),
    CONSTRAINT uq_orders_id_drop UNIQUE (id, drop_id),
    CONSTRAINT fk_orders_buyer FOREIGN KEY (buyer_id) REFERENCES users (id),
    CONSTRAINT fk_orders_drop FOREIGN KEY (drop_id) REFERENCES drops (id),
    CONSTRAINT ck_orders_status CHECK (
        status IN ('PAYMENT_PENDING', 'PAID', 'EXPIRED', 'PREPARING', 'SHIPPED', 'DELIVERED', 'CANCELED')
    ),
    CONSTRAINT ck_orders_amounts CHECK (
        items_amount >= 0
        AND shipping_amount >= 0
        AND total_amount = items_amount + shipping_amount
    ),
    CONSTRAINT ck_orders_payment_expiry CHECK (payment_expires_at > created_at),
    CONSTRAINT ck_orders_paid_at CHECK (
        status NOT IN ('PAID', 'PREPARING', 'SHIPPED', 'DELIVERED') OR paid_at IS NOT NULL
    ),
    CONSTRAINT ck_orders_canceled_at CHECK (status <> 'CANCELED' OR canceled_at IS NOT NULL)
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    drop_id BIGINT NOT NULL,
    option_id BIGINT NOT NULL,
    option_name_snapshot VARCHAR(200) NOT NULL,
    unit_price BIGINT NOT NULL,
    quantity INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_order_items PRIMARY KEY (id),
    CONSTRAINT uq_order_items_order_option UNIQUE (order_id, option_id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id, drop_id)
        REFERENCES orders (id, drop_id),
    CONSTRAINT fk_order_items_option FOREIGN KEY (option_id, drop_id)
        REFERENCES drop_options (id, drop_id),
    CONSTRAINT ck_order_items_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0)
);

CREATE TABLE stock_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_item_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'HELD',
    expires_at TIMESTAMPTZ NOT NULL,
    committed_at TIMESTAMPTZ,
    released_at TIMESTAMPTZ,
    release_reason VARCHAR(30),
    release_destination VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_stock_reservations PRIMARY KEY (id),
    CONSTRAINT uq_stock_reservations_order_item UNIQUE (order_item_id),
    CONSTRAINT fk_stock_reservations_item FOREIGN KEY (order_item_id) REFERENCES order_items (id),
    CONSTRAINT ck_stock_reservations_status CHECK (status IN ('HELD', 'COMMITTED', 'RELEASED')),
    CONSTRAINT ck_stock_reservations_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_stock_reservations_release_reason CHECK (
        release_reason IS NULL OR release_reason IN ('PAYMENT_FAILED', 'EXPIRED', 'ORDER_CANCELED')
    ),
    CONSTRAINT ck_stock_reservations_destination CHECK (
        release_destination IS NULL OR release_destination IN ('AVAILABLE', 'WITHHELD')
    ),
    CONSTRAINT ck_stock_reservations_state_fields CHECK (
        (status = 'HELD' AND committed_at IS NULL AND released_at IS NULL
            AND release_reason IS NULL AND release_destination IS NULL)
        OR (status = 'COMMITTED' AND committed_at IS NOT NULL AND released_at IS NULL
            AND release_reason IS NULL AND release_destination IS NULL)
        OR (status = 'RELEASED' AND released_at IS NOT NULL
            AND release_reason IS NOT NULL AND release_destination IS NOT NULL)
    )
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    provider VARCHAR(30) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    provider_payment_id VARCHAR(200),
    amount BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    reconciliation_status VARCHAR(20) NOT NULL DEFAULT 'NONE',
    reconciliation_reason TEXT,
    approved_at TIMESTAMPTZ,
    canceled_at TIMESTAMPTZ,
    failure_code VARCHAR(100),
    failure_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payments PRIMARY KEY (id),
    CONSTRAINT uq_payments_idempotency UNIQUE (provider, idempotency_key),
    CONSTRAINT uq_payments_provider_payment UNIQUE (provider, provider_payment_id),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT ck_payments_provider CHECK (provider IN ('MOCK', 'TOSS')),
    CONSTRAINT ck_payments_amount CHECK (amount >= 0),
    CONSTRAINT ck_payments_status CHECK (
        status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'UNKNOWN', 'CANCELED')
    ),
    CONSTRAINT ck_payments_reconciliation CHECK (
        reconciliation_status IN ('NONE', 'REQUIRED', 'RESOLVED')
    ),
    CONSTRAINT ck_payments_approved_at CHECK (
        status NOT IN ('SUCCEEDED', 'CANCELED') OR approved_at IS NOT NULL
    ),
    CONSTRAINT ck_payments_canceled_at CHECK (status <> 'CANCELED' OR canceled_at IS NOT NULL),
    CONSTRAINT ck_payments_unknown_reconciliation CHECK (
        status <> 'UNKNOWN' OR reconciliation_status = 'REQUIRED'
    )
);

CREATE TABLE payment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_id BIGINT NOT NULL,
    event_key VARCHAR(200) NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    source VARCHAR(20) NOT NULL,
    processing_result VARCHAR(30) NOT NULL,
    payload JSONB NOT NULL,
    occurred_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payment_events PRIMARY KEY (id),
    CONSTRAINT uq_payment_events_key UNIQUE (payment_id, event_key),
    CONSTRAINT fk_payment_events_payment FOREIGN KEY (payment_id) REFERENCES payments (id),
    CONSTRAINT ck_payment_events_source CHECK (source IN ('API', 'WEBHOOK', 'RECONCILIATION')),
    CONSTRAINT ck_payment_events_result CHECK (
        processing_result IN ('APPLIED', 'REJECTED', 'RECONCILIATION_REQUIRED')
    )
);

CREATE TABLE payment_cancellations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_id BIGINT NOT NULL,
    requested_by BIGINT,
    purpose VARCHAR(30) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    amount BIGINT NOT NULL,
    reason TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
    provider_cancel_id VARCHAR(200),
    completed_at TIMESTAMPTZ,
    failure_code VARCHAR(100),
    attempt_count INT NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payment_cancellations PRIMARY KEY (id),
    CONSTRAINT uq_payment_cancellations_idempotency UNIQUE (idempotency_key),
    CONSTRAINT fk_payment_cancellations_payment FOREIGN KEY (payment_id) REFERENCES payments (id),
    CONSTRAINT fk_payment_cancellations_requester FOREIGN KEY (requested_by) REFERENCES users (id),
    CONSTRAINT ck_payment_cancellations_purpose CHECK (
        purpose IN ('ORDER_CANCEL', 'LATE_APPROVAL_COMPENSATION')
    ),
    CONSTRAINT ck_payment_cancellations_amount CHECK (amount >= 0),
    CONSTRAINT ck_payment_cancellations_status CHECK (
        status IN ('REQUESTED', 'UNKNOWN', 'SUCCEEDED', 'FAILED')
    ),
    CONSTRAINT ck_payment_cancellations_attempts CHECK (attempt_count >= 0),
    CONSTRAINT ck_payment_cancellations_completed CHECK (
        status NOT IN ('SUCCEEDED', 'FAILED') OR completed_at IS NOT NULL
    )
);

CREATE TABLE shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    carrier_code VARCHAR(50) NOT NULL,
    tracking_number VARCHAR(100) NOT NULL,
    shipped_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_shipments PRIMARY KEY (id),
    CONSTRAINT uq_shipments_order UNIQUE (order_id),
    CONSTRAINT fk_shipments_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT ck_shipments_delivery_time CHECK (
        delivered_at IS NULL OR (shipped_at IS NOT NULL AND delivered_at >= shipped_at)
    )
);

