-- 수요 분석 판매 계획(GR-143, ERD.md 1.7). 계산 결과 스냅샷과 판매자 결정만 기록하고 재고·DROP은 바꾸지 않는다.
CREATE TABLE demand_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    drop_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL,
    assumptions JSONB NOT NULL,
    conversion_basis VARCHAR(20),
    result JSONB NOT NULL,
    calculation_version VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    decided_quantities JSONB,
    decision_reason VARCHAR(500),
    decided_at TIMESTAMPTZ,
    explanation_status VARCHAR(20) NOT NULL,
    explanation JSONB,
    llm_model VARCHAR(100),
    prompt_version VARCHAR(20),
    explanation_tokens INT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_demand_plans PRIMARY KEY (id),
    CONSTRAINT uq_demand_plans_public_id UNIQUE (public_id),
    CONSTRAINT fk_demand_plans_drop FOREIGN KEY (drop_id) REFERENCES drops (id),
    CONSTRAINT fk_demand_plans_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT ck_demand_plans_conversion_basis CHECK (
        conversion_basis IS NULL OR conversion_basis IN ('OWN', 'MARKET', 'SELLER_INPUT')
    ),
    CONSTRAINT ck_demand_plans_status CHECK (status IN ('DRAFT', 'ACCEPTED', 'MODIFIED', 'REJECTED')),
    -- 결정 필드는 결정한 계획에만 있고, 판매자가 정한 수량은 MODIFIED에만 있다
    CONSTRAINT ck_demand_plans_decision CHECK (
        (status = 'DRAFT' AND decided_at IS NULL AND decided_quantities IS NULL AND decision_reason IS NULL)
        OR (status IN ('ACCEPTED', 'REJECTED') AND decided_at IS NOT NULL AND decided_quantities IS NULL)
        OR (status = 'MODIFIED' AND decided_at IS NOT NULL AND decided_quantities IS NOT NULL)
    ),
    CONSTRAINT ck_demand_plans_explanation_status CHECK (
        explanation_status IN ('PENDING', 'GENERATED', 'DISCARDED', 'FAILED', 'DISABLED')
    ),
    -- 수치 검증을 통과한 설명만 저장한다(DEMAND.md 3절)
    CONSTRAINT ck_demand_plans_explanation CHECK (
        (explanation_status = 'GENERATED') = (explanation IS NOT NULL)
    ),
    CONSTRAINT ck_demand_plans_explanation_tokens CHECK (explanation_tokens IS NULL OR explanation_tokens >= 0)
);

CREATE INDEX idx_demand_plans_drop_created ON demand_plans (drop_id, created_at, id);

