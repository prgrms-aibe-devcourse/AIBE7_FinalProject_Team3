-- 공개 시점 재고 추천 기록(GR-167, ERD.md 1.7). DROP당 한 건, 추가만 하고 고치지 않는다.
CREATE TABLE drop_stock_recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    drop_id BIGINT NOT NULL,
    calculation_version VARCHAR(20) NOT NULL,
    basis VARCHAR(20),
    result JSONB NOT NULL,
    recommended_total INT,
    prepared_total INT NOT NULL,
    prepared_quantities JSONB NOT NULL,
    applied BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_drop_stock_recommendations PRIMARY KEY (id),
    CONSTRAINT uq_drop_stock_recommendations_drop UNIQUE (drop_id),
    CONSTRAINT fk_drop_stock_recommendations_drop FOREIGN KEY (drop_id) REFERENCES drops (id),
    CONSTRAINT ck_drop_stock_recommendations_basis CHECK (basis IS NULL OR basis IN ('OWN', 'MARKET')),
    CONSTRAINT ck_drop_stock_recommendations_totals CHECK (
        prepared_total >= 0 AND (recommended_total IS NULL OR recommended_total >= 0)
    ),
    -- 기준이 없으면 추천 수량이 없고, 추천이 없으면 적용했다고 볼 수 없다
    CONSTRAINT ck_drop_stock_recommendations_applied CHECK (
        (basis IS NULL) = (recommended_total IS NULL) AND (recommended_total IS NOT NULL OR applied = FALSE)
    )
);
