-- 수요 분석을 참고용으로 전환한다(GR-175, ERD.md 1.7, 수요 분석 API 2.3).
-- 판매자가 계획을 저장하고 결정을 기록하던 demand_plans(V24)를 삭제한다. 결정은 재고를 바꾸지 않는 기록이라
-- 판매자에게 효과가 없었고, 생성 단계 재고 추천(GR-167)과 역할이 겹쳤다. 저장된 계획 데이터도 함께 지운다.
-- V24가 함께 만든 idx_drops_category_closed는 전환율 표본 조회에 계속 쓰므로 남긴다.
DROP TABLE demand_plans;

-- 판매 시작(WISH → GRAB) 시점 수요 분석 기록. DROP당 한 건, 추가만 하고 고치지 않는다.
-- 종료 후 실제 판매량과 비교해 예측 정확도를 평가한다.
CREATE TABLE demand_analysis_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    drop_id BIGINT NOT NULL,
    calculation_version VARCHAR(20) NOT NULL,
    conversion_basis VARCHAR(20),
    result JSONB NOT NULL,
    active_wish_count INT NOT NULL,
    expected_total INT,
    recommended_total INT,
    prepared_total INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_demand_analysis_snapshots PRIMARY KEY (id),
    CONSTRAINT uq_demand_analysis_snapshots_drop UNIQUE (drop_id),
    CONSTRAINT fk_demand_analysis_snapshots_drop FOREIGN KEY (drop_id) REFERENCES drops (id),
    -- 기본 가정으로만 계산하므로 판매자 입력 전환율(SELLER_INPUT)은 없다
    CONSTRAINT ck_demand_analysis_snapshots_basis CHECK (
        conversion_basis IS NULL OR conversion_basis IN ('OWN', 'MARKET')
    ),
    CONSTRAINT ck_demand_analysis_snapshots_totals CHECK (
        active_wish_count >= 0 AND prepared_total >= 0
        AND (expected_total IS NULL OR expected_total >= 0)
        AND (recommended_total IS NULL OR recommended_total >= 0)
    ),
    -- 예상·추천 수량은 함께 있거나 함께 없다. 기준이 없으면 수량도 없다(WISH가 없으면 기준이 있어도 수량이 없다)
    CONSTRAINT ck_demand_analysis_snapshots_plan CHECK (
        (expected_total IS NULL) = (recommended_total IS NULL)
        AND (conversion_basis IS NOT NULL OR expected_total IS NULL)
    )
);
