-- 수요 분석 설명(GR-146, ERD.md 1.7, 수요 분석 API 3.4). 판매자가 요청한 가정의 분석 결과를 LLM으로 설명한 결과다.
-- 같은 DROP·같은 입력이면 다시 부르지 않도록 (drop_id, input_hash)당 한 건만 둔다.
-- 형식·수치 검증을 통과한 GENERATED와 버린 DISCARDED만 남기고, 응답 원문은 저장하지 않는다.
CREATE TABLE demand_explanations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    drop_id BIGINT NOT NULL,
    input_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    explanation JSONB,
    llm_model VARCHAR(100),
    prompt_version VARCHAR(20) NOT NULL,
    tokens INT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_demand_explanations PRIMARY KEY (id),
    CONSTRAINT uq_demand_explanations_drop_input UNIQUE (drop_id, input_hash),
    CONSTRAINT fk_demand_explanations_drop FOREIGN KEY (drop_id) REFERENCES drops (id),
    CONSTRAINT ck_demand_explanations_status CHECK (status IN ('GENERATED', 'DISCARDED')),
    -- 검증을 통과한 설명만 저장한다(수요 분석 API 3.3)
    CONSTRAINT ck_demand_explanations_explanation CHECK ((status = 'GENERATED') = (explanation IS NOT NULL)),
    CONSTRAINT ck_demand_explanations_tokens CHECK (tokens IS NULL OR tokens >= 0)
);
